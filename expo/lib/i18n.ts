const dicts: Record<LangCode, Dict> = { en, es, fr, ar, sw, pt, hi, zh, de, it, ja, ru };

/** Substitute `{token}` placeholders. */
function format(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, k: string) =>
    vars[k] !== undefined && vars[k] !== null ? String(vars[k]) : `{${k}}`
  );
}

/**
 * Translate a key into the given language.
 * Falls back to English, then to the raw key when neither dict has it.
 */
export function t(key: string, lang: LangCode = "en", vars?: Record<string, string | number>): string {
  const raw = dicts[lang]?.[key] ?? dicts.en[key] ?? key;
  return format(raw, vars);
}

export function getLanguage(code: LangCode): LanguageDef {
  return LANGUAGES.find((l) => l.code === code) ?? LANGUAGES[0];
}

/** True if the language is right-to-left. */
export function isRTL(code: LangCode): boolean {
  return Boolean(getLanguage(code).rtl);
}

/**
 * Best-effort device language detection. Returns the first supported language
 * the device prefers, otherwise English.
 */
export function detectDeviceLanguage(): LangCode {
  try {
    const locales = Localization.getLocales();
    for (const l of locales) {
      const code = (l.languageCode ?? "").toLowerCase();
      const hit = LANGUAGES.find((x) => x.code === code);
      if (hit) return hit.code;
    }
  } catch {
    // ignore
  }
  return "en";
}

/**
 * Apply the language's RTL direction to React Native's I18nManager. Returns
 * `true` when the direction actually flipped (caller may want to reload).
 */
export function applyTextDirection(code: LangCode): boolean {
  const rtl = isRTL(code);
  try {
    if (I18nManager.isRTL !== rtl) {
      I18nManager.allowRTL(rtl);
      I18nManager.forceRTL(rtl);
      return true;
    }
  } catch {
    // ignore
  }
  return false;
}

// ---------- Locale-aware formatters ----------

function localeFor(code: LangCode): string {
  return getLanguage(code).locale;
}

export function formatNumber(value: number, code: LangCode = "en"): string {
  try {
    return new Intl.NumberFormat(localeFor(code)).format(value);
  } catch {
    return String(value);
  }
}

export function formatCurrency(value: number, currency: string = "USD", code: LangCode = "en"): string {
  try {
    return new Intl.NumberFormat(localeFor(code), { style: "currency", currency }).format(value);
  } catch {
    return `${currency} ${value}`;
  }
}

export function formatDate(
  ts: number | Date,
  code: LangCode = "en",
  opts: Intl.DateTimeFormatOptions = { year: "numeric", month: "short", day: "numeric" }
): string {
  try {
    return new Intl.DateTimeFormat(localeFor(code), opts).format(ts instanceof Date ? ts : new Date(ts));
  } catch {
    return new Date(ts).toDateString();
  }
}

export function formatTime(ts: number | Date, code: LangCode = "en"): string {
  return formatDate(ts, code, { hour: "numeric", minute: "2-digit" });
}

export function formatDateTime(ts: number | Date, code: LangCode = "en"): string {
  return formatDate(ts, code, {
    month: "short",
    day: "numeric",
    hour: "numeric",
    minute: "2-digit",
  });
}
